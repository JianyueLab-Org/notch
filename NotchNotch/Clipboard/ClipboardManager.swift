//
//  ClipboardManager.swift
//  NotchNotch
//
//  Tracks pasteboard changes, maintains history carousel items,
//  detects source application icons, and handles clipboard persistence.
//

import AppKit
import Combine
import Foundation
import OSLog

/// `nonisolated` so the history can be encoded off the main actor.
nonisolated struct ClipboardItem: Identifiable, Codable, Equatable, Sendable {
    let id: UUID
    let text: String
    var timestamp: Date
    var copyCount: Int
    var appBundleId: String?
    var appName: String?

    @MainActor
    var ageString: String {
        let elapsed = max(0, -timestamp.timeIntervalSinceNow)
        let isZh = LocalizationManager.shared.isChinese
        if elapsed < 60 {
            return isZh ? "刚刚" : "now"
        } else if elapsed < 3600 {
            let mins = max(1, Int(elapsed / 60))
            return isZh ? "\(mins)分前" : "\(mins)m"
        } else if elapsed < 86400 {
            let hours = max(1, Int(elapsed / 3600))
            return isZh ? "\(hours)时前" : "\(hours)h"
        } else {
            let days = max(1, Int(elapsed / 86400))
            return isZh ? "\(days)天前" : "\(days)d"
        }
    }

    @MainActor
    var appIcon: NSImage? {
        if let appBundleId,
           let appUrl = NSWorkspace.shared.urlForApplication(withBundleIdentifier: appBundleId) {
            return NSWorkspace.shared.icon(forFile: appUrl.path)
        }
        return nil
    }

    static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        lhs.id == rhs.id && lhs.text == rhs.text && lhs.copyCount == rhs.copyCount
    }
}

@MainActor
final class ClipboardManager: ObservableObject {

    static let shared = ClipboardManager()

    static let maxItemsOptions: [Int] = [5, 10, 15, 20]
    static let defaultMaxItems: Int = 10
    static let maxItemsKey = "co.jianyuelab.NotchNotch.clipboardMaxItems"
    static let monitoringEnabledKey = "co.jianyuelab.NotchNotch.clipboardMonitoringEnabled"

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var maxItems: Int = defaultMaxItems
    @Published private(set) var isMonitoringEnabled: Bool = true

    private var lastChangeCount: Int = -1
    private var pollTimer: Timer?
    private let persistenceURL: URL

    /// Serial, so an older snapshot can never land on disk after a newer one.
    private static let persistenceQueue = DispatchQueue(
        label: "co.jianyuelab.NotchNotch.clipboard-persistence", qos: .utility)

    /// The nspasteboard.org markers password managers and generators set so that
    /// clipboard tools neither show nor keep what they copy.
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let appDir = appSupport.appendingPathComponent("co.jianyuelab.NotchNotch", isDirectory: true)
        try? FileManager.default.createDirectory(at: appDir, withIntermediateDirectories: true)
        self.persistenceURL = appDir.appendingPathComponent("clipboard_history.json")

        let storedMax = UserDefaults.standard.integer(forKey: Self.maxItemsKey)
        if Self.maxItemsOptions.contains(storedMax) {
            self.maxItems = storedMax
        } else {
            self.maxItems = Self.defaultMaxItems
            UserDefaults.standard.set(Self.defaultMaxItems, forKey: Self.maxItemsKey)
        }

        if UserDefaults.standard.object(forKey: Self.monitoringEnabledKey) != nil {
            self.isMonitoringEnabled = UserDefaults.standard.bool(forKey: Self.monitoringEnabledKey)
        } else {
            self.isMonitoringEnabled = true
        }

        loadPersisted()
        if FileManager.default.fileExists(atPath: persistenceURL.path) {
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: persistenceURL.path)
        }
        if isMonitoringEnabled {
            startMonitoring()
        }
    }

    func setMonitoringEnabled(_ enabled: Bool) {
        isMonitoringEnabled = enabled
        UserDefaults.standard.set(enabled, forKey: Self.monitoringEnabledKey)
        if enabled {
            startMonitoring()
        } else {
            stopMonitoring()
        }
    }

    func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
    }

    func startMonitoring() {
        lastChangeCount = NSPasteboard.general.changeCount

        // If history is empty on first boot, record current pasteboard
        if items.isEmpty {
            recordCurrentPasteboardIfAvailable()
        }

        // Poll pasteboard every 0.6 seconds in common runloop mode
        pollTimer?.invalidate()
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.pollPasteboard()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
    }

    func pollPasteboard() {
        guard isMonitoringEnabled else { return }
        let currentCount = NSPasteboard.general.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        guard let text = Self.recordableString(from: NSPasteboard.general) else { return }

        // Identify frontmost application that performed the copy
        let frontApp = NSWorkspace.shared.frontmostApplication
        let isSelf = frontApp?.bundleIdentifier == Bundle.main.bundleIdentifier
        let bundleId = isSelf ? nil : frontApp?.bundleIdentifier
        let appName = isSelf ? nil : frontApp?.localizedName

        record(text: text, bundleId: bundleId, appName: appName)
    }

    func record(text: String, bundleId: String?, appName: String?) {
        // If string already exists in history, bump copyCount and move to front
        if let existingIndex = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: existingIndex)
            item.copyCount += 1
            item.timestamp = Date()
            if let bundleId { item.appBundleId = bundleId }
            if let appName { item.appName = appName }
            items.insert(item, at: 0)
        } else {
            let newItem = ClipboardItem(
                id: UUID(),
                text: text,
                timestamp: Date(),
                copyCount: 1,
                appBundleId: bundleId,
                appName: appName
            )
            items.insert(newItem, at: 0)
        }
        if items.count > maxItems {
            items = Array(items.prefix(maxItems))
        }
        savePersisted()
    }

    func updateMaxItems(_ count: Int) {
        guard Self.maxItemsOptions.contains(count) else { return }
        maxItems = count
        UserDefaults.standard.set(count, forKey: Self.maxItemsKey)
        if items.count > count {
            items = Array(items.prefix(count))
            savePersisted()
        }
    }

    func copyToPasteboard(item: ClipboardItem) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(item.text, forType: .string)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func clearAll() {
        items.removeAll()
        savePersisted()
    }


    private func recordCurrentPasteboardIfAvailable() {
        if let text = Self.recordableString(from: NSPasteboard.general) {
            record(text: text, bundleId: nil, appName: nil)
        }
    }

    /// The pasteboard's text, or nil when it is empty, marked as a secret, or too big
    /// to keep (every copy rewrites the whole history file).
    private static func recordableString(from pasteboard: NSPasteboard) -> String? {
        if let types = pasteboard.types, !excludedTypes.isDisjoint(with: types) {
            return nil
        }
        guard let text = pasteboard.string(forType: .string),
              text.utf8.count <= NotchConfiguration.clipboardMaxItemBytes,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return nil
        }
        return text
    }

    // MARK: - Persistence

    private func loadPersisted() {
        guard FileManager.default.fileExists(atPath: persistenceURL.path),
              let data = try? Data(contentsOf: persistenceURL),
              var decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else {
            return
        }
        decoded.removeAll { $0.text.utf8.count > NotchConfiguration.clipboardMaxItemBytes }
        if decoded.count > maxItems {
            items = Array(decoded.prefix(maxItems))
            savePersisted()
        } else {
            items = decoded
        }
    }

    private func savePersisted() {
        let snapshot = items
        let url = persistenceURL
        Self.persistenceQueue.async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: url, options: .atomic)
            // The history holds whatever the user copied, including secrets.
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }
}
